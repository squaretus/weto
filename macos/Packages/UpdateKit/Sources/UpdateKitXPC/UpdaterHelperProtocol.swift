import Foundation

/// XPC-протокол привилегированного демона обновления.
///
/// `performUpdate` намеренно **не принимает** ни ссылки, ни версии: демон сам
/// спрашивает источник релизов и сам решает, что установить. Иначе любой процесс,
/// прошедший авторизацию, мог бы попросить root поставить произвольный пакет.
///
/// Поверхность держится минимальной осознанно: каждый метод здесь исполняет
/// процесс с правами root. `installState` только читает — этим он и оправдан.
@objc public protocol UpdaterHelperProtocol {

    /// Запускает скачивание и установку. Отвечает сразу: nil — установка начата.
    func performUpdate(reply: @escaping (String?) -> Void)

    /// Ход установки: код фазы, доля скачанного 0…1, текст провала.
    /// Ответ на `performUpdate` уходит до скачивания, поэтому без этого метода
    /// ни прогресс, ни провал не видны никому, кроме unified log.
    func installState(reply: @escaping (Int, Double, String?) -> Void)

    /// Снимает сам себя: выгружает задание, удаляет свой plist, бинарник
    /// и рабочий каталог. Нужен, потому что приложение работает без прав
    /// и убрать файлы из /Library не может.
    func uninstallHelper(reply: @escaping (String?) -> Void)
}
