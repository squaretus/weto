#!/bin/bash
# Удаление weto.
#
# Снимает ровно то, что ставил установщик, плюс состояние приложения.
# Расхождение установщика и деинсталлятора на macOS уже случалось — после
# удаления оставался живой демон, — поэтому здесь оно проверяется машинно
# контрактом install-contract.sh.
set -u

DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE="${XDG_STATE_HOME:-$HOME/.local/state}"
CACHE="${XDG_CACHE_HOME:-$HOME/.cache}"
BIN="$HOME/.local/bin"

echo "Удаление weto..."

# Кого не трогать. Пропуск нужен ровно одному — тому, кто нас и запустил:
# кнопка «Удалить приложение…» зовёт этот скрипт синхронно из самого GUI,
# а GUI подходит под все наши приметы — имя процесса weto и файл под
# $DATA/weto/. SIGTERM самому себе приложение уводит в штатный выход, но
# сигнал ждёт в очереди главного цикла и разбирается сразу, как вернётся
# вызов: при неудачном удалении сообщение об ошибке появлялось бы и тут же
# исчезало вместе с приложением, а оно обязано остаться на экране. Из
# терминала переменной нет, и поведение там прежнее.
SKIP=" ${WETO_UNINSTALL_SKIP_PID:-} "
SKIP="${SKIP//,/ }"

# Работающая копия завершается: иначе она перепишет настройки, которые
# мы вот-вот удалим, и воссоздаст каталоги, которые мы удаляем.
#
# Матчить по командной строке нельзя: процесс запускают через $BIN/weto,
# а искали путь через current — и pkill молча не находил ничего. Имя
# процесса плюс проверка, что это именно наш файл, сужают поиск до своих;
# всё остальное решает пропуск выше.
for pid in $(pgrep -x weto 2>/dev/null || true); do
    case "$SKIP" in
        *" $pid "*) continue ;;
    esac

    # Сперва -f, следом простой readlink. Разница видна только у копии, под
    # которой снесли каталог версии целиком, — это повторный прогон удаления
    # и прогон после вычистки старой версии обновлением. Одного удалённого
    # файла мало: `readlink -f` разрешает путь, у которого нет только
    # последнего звена, и честно отвечает «… (deleted)». А вот когда нет
    # и родительских каталогов, разрешать ему нечего — он отдаёт пустую
    # строку, копия не совпадает ни с чем, переживает удаление и воссоздаёт
    # снесённые каталоги, то есть делает ровно то, ради чего этот блок
    # и написан. Простой readlink отдаёт ссылку как есть, с тем же суффиксом
    # « (deleted)», а сравнение идёт по префиксу — суффикс ему не мешает.
    exe="$(readlink -f "/proc/$pid/exe" 2>/dev/null || true)"
    [ -n "$exe" ] || exe="$(readlink "/proc/$pid/exe" 2>/dev/null || true)"
    case "$exe" in
        "$DATA/weto/"*) kill "$pid" 2>/dev/null || true ;;
    esac
done
sleep 1

rm -f "$BIN/weto"
rm -rf "$DATA/weto"
rm -f "$DATA/applications/weto.desktop"
rm -f "$DATA/icons/hicolor/scalable/apps/weto.svg"
rm -f "$CONFIG/autostart/weto.desktop"
rm -rf "$CONFIG/weto"
rm -rf "$STATE/weto"
rm -rf "$CACHE/weto"

# Токен мог уехать в Secret Service, если он в системе есть.
command -v secret-tool >/dev/null 2>&1 && \
    secret-tool clear service weto account ipinfo 2>/dev/null || true

update-desktop-database "$DATA/applications" 2>/dev/null || true

echo "weto удалён."
