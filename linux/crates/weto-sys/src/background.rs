//! Фоновая дорожка: куда уходит работа, которой такт не ждёт.
//!
//! Нужна ровно одному делу — сетевой пробе. Такт охраны идёт раз в секунду
//! (а под красным статусом раз в 250 мс) против пятисекундного таймаута ipinfo,
//! и запрос, выполненный внутри такта, означал бы, что цель, запущенная под
//! паузой или под запретом, живёт всё время ожидания ответа. На macOS проба —
//! `Task`, а ответ приходит отдельным входом; здесь ту же роль играет поток.
//!
//! Граница отдельная, потому что подменяется она как всякая другая: тесту нужен
//! детерминированный порядок «такт прошёл — ответ пришёл», а не гонка с планировщиком.

pub trait BackgroundDispatching: Send + Sync {
    /// Взять работу и вернуть управление немедленно.
    fn dispatch(&self, job: Box<dyn FnOnce() + Send + 'static>);
}

/// Дорожка из настоящего потока — то, чем она и является в приложении.
///
/// Поток на работу, а не пул: работ в полёте не бывает больше одной — за этим
/// следит сам вызывающий, — и держать ради неё живой поток дороже, чем создавать
/// его раз в пять секунд.
pub struct ThreadDispatcher {
    name: String,
}

impl ThreadDispatcher {
    pub fn named(name: &str) -> ThreadDispatcher {
        ThreadDispatcher {
            name: name.to_string(),
        }
    }
}

impl BackgroundDispatching for ThreadDispatcher {
    fn dispatch(&self, job: Box<dyn FnOnce() + Send + 'static>) {
        match std::thread::Builder::new()
            .name(self.name.clone())
            .spawn(job)
        {
            Ok(_) => {}
            // Поток не создался — работа не выполнится вовсе, и молчать об этом
            // нельзя: у пробы это означает «вердикта не будет, пока не повезёт
            // следующему такту».
            Err(error) => eprintln!(
                "weto: фоновая дорожка «{}» не создалась: {error}",
                self.name
            ),
        }
    }
}
