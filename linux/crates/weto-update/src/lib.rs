//! Самообновление без прав root.
//!
//! # Чем это отличается от macOS
//!
//! Там обновление ставит `installer` в `/Applications`, для чего нужен root,
//! и потому существует привилегированный демон, XPC-протокол и перепроверка
//! релиза самим демоном. Здесь установка идёт в домашний каталог: root не нужен,
//! и вся эта половина механизма отсутствует как класс.
//!
//! Защита при этом остаётся ровно та же, что на macOS: https и список хостов
//! доставки GitHub. Подписи там нет — `.pkg` не подписан, а ad-hoc `codesign`
//! подтверждает целостность бандла, но не происхождение. Заводить подпись
//! на одной платформе значило бы развести продукт по уровню защиты
//! без причины, лежащей в самой платформе.

pub mod checker;
pub mod installer;
pub mod layout;
pub mod policy;
