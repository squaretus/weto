//! Содержимое окна настроек обязано держать свою ширину само.
//!
//! Размер окна решает не приложение: тайловый композитор растягивает его
//! на всю ячейку, и `default_width` там не значит ничего. Строки карточек
//! честно `hexpand`-ятся, поэтому вёрстка расползалась — подпись у левого
//! края, тумблер у правого, между ними пустая полоса во весь экран.

use gtk4::prelude::*;

use weto_ui::components as ui;

/// Тайловый композитор растягивает окно на всю ячейку, и строки карточек
/// расползались: подпись у левого края, тумблер у правого, между ними пустая
/// полоса во весь экран. Содержимое обязано держать свою ширину само.
#[test]
fn the_content_keeps_its_width_in_a_wide_window() {
    gtk4::init().expect("GTK не поднялся: тестам нужен дисплей, запускать под Xvfb");
    let column = ui::content_column(&gtk4::Label::new(Some("строка")));

    assert_eq!(column.halign(), gtk4::Align::Center);
    assert_eq!(column.width_request(), ui::WINDOW_WIDTH);
    assert!(!column.hexpands());
}
