//! Правило времени жизни приложения: переживает ли оно свои окна.
//!
//! Проверяется без дисплея и без шины намеренно. Поведение GTK-приложения
//! целиком тестом не покрыть — а решение, от которого оно зависит, покрыть
//! можно, и оно того стоит: ошибка здесь стоит пользователю охраны.

use weto_app::lifecycle::holds_application;

/// Трей есть — закрытие окна обязано быть скрытием: иконка остаётся, охрана
/// работает. Иначе человек «просто закрыл окно» и остался без защиты, ничего
/// об этом не узнав.
#[test]
fn with_a_tray_the_application_outlives_its_windows() {
    assert!(holds_application(true));
}

/// Трея нет — удерживать нельзя: приложение без окон и без иконки закрыть было
/// бы нечем, кроме kill. Прежнее поведение остаётся.
#[test]
fn without_a_tray_the_last_window_still_closes_the_application() {
    assert!(!holds_application(false));
}
