//! Правило времени жизни приложения: переживает ли оно свои окна.
//!
//! Проверяется без дисплея и без шины намеренно — `gio::Application` хватает
//! и того, и другого не требует. Что удержание меняет на самом деле, проверяет
//! `tests/held_window.rs` под GTK; здесь — само решение, взять расписку или
//! не взять. Ошибка в нём стоит пользователю охраны.

use gtk4::gio::{Application, ApplicationFlags};

use weto_app::lifecycle::hold_if_tray;

/// Приложение для проверки. Без шины: в контейнере её нет, а уникальность
/// здесь ни при чём.
fn application() -> Application {
    Application::builder()
        .application_id("com.weto.app.tests")
        .flags(ApplicationFlags::NON_UNIQUE)
        .build()
}

/// Трей есть — расписка обязана быть взята: закрытие окна становится скрытием,
/// иконка остаётся, охрана работает. Иначе человек «просто закрыл окно»
/// и остался без защиты, ничего об этом не узнав.
#[test]
fn with_a_tray_the_application_outlives_its_windows() {
    assert!(
        hold_if_tray(&application(), true).is_some(),
        "расписка не взята при живом трее: крестик на окне снимет охрану"
    );
}

/// Трея нет — расписки быть не должно. Удержанное приложение без окон невидимо
/// совсем, а невидимый процесс, который сам завершает чужие программы,
/// объяснить пользователю нечем. Прежнее поведение остаётся.
#[test]
fn without_a_tray_the_last_window_still_closes_the_application() {
    assert!(
        hold_if_tray(&application(), false).is_none(),
        "расписка взята без трея: weto остался бы сторожить втайне"
    );
}
