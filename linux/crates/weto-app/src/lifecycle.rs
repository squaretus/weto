//! Время жизни приложения: переживает ли процесс свои окна.
//!
//! GApplication завершается сам, когда закрылось последнее окно. Для weto это
//! означало, что крестик на окне снимает охрану: иконка из трея исчезала,
//! цели оставались без присмотра, и человек об этом не узнавал — он ведь
//! просто закрыл окно. Отсюда удержание (`hold`): закрытие окна становится
//! скрытием, а выход остаётся там, где его и ищут, — пункт «Выход» в трее
//! и кнопка «Закрыть приложение» в настройках.

/// Держать ли приложение живым после закрытия последнего окна.
///
/// Удержание условно, и условие ровно одно: поднялась ли иконка в трее.
/// В окружении без трея (ванильный GNOME без расширений) удержанное
/// приложение без окон закрыть было бы нечем, кроме `kill`: ни иконки,
/// ни пункта «Выход» у пользователя нет, а окна он только что закрыл. Там
/// прежнее поведение — «последнее окно закрывает приложение» — не беда,
/// а единственный доступный выход.
///
/// На воронку выхода правило не влияет: `app.quit()` проходит через
/// `connect_shutdown` и при удержании, и обязательство вернуть цели
/// из паузы исполняется там же, где и раньше.
pub fn holds_application(tray_installed: bool) -> bool {
    tray_installed
}
