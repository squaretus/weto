//! Время жизни приложения и его окон.
//!
//! GApplication завершается сам, когда закрылось последнее окно. Для weto это
//! означало, что крестик на окне снимает охрану: иконка из трея исчезала,
//! цели оставались без присмотра, и человек об этом не узнавал — он ведь
//! просто закрыл окно. Отсюда удержание (`hold`): закрытие окна становится
//! скрытием, а выход остаётся там, где его и ищут, — пункт «Выход» в трее
//! и кнопка «Закрыть приложение» в настройках.
//!
//! Удержание же заводит здесь и второе правило — про такты окон. Пока процесс
//! умирал вместе с последним окном, вечный `timeout_add_local` не стоил ничего:
//! его уносил выход. Теперь окна открываются и закрываются сколько угодно раз
//! над живым процессом, и такт, переживший своё окно, — это утечка: замыкание
//! держит виджеты разрушенного окна, дёргает состояние под мьютексом и
//! пересобирает то, чего давно никто не видит. Поэтому такт окна заводят
//! только через `window_tick`.

use std::cell::Cell;
use std::rc::Rc;
use std::time::Duration;

use gtk4::glib::ControlFlow;
use gtk4::prelude::*;
use gtk4::ApplicationWindow;

/// Держать ли приложение живым после закрытия последнего окна.
///
/// Удержание условно, и условие ровно одно: поднялась ли иконка в трее.
/// В окружении без трея (ванильный GNOME без расширений) удержанное
/// приложение без окон закрыть было бы нечем, кроме `kill`: ни иконки,
/// ни пункта «Выход» у пользователя нет, а окна он только что закрыл. Там
/// прежнее поведение — «последнее окно закрывает приложение» — не беда,
/// а единственный доступный выход.
///
/// На воронку выхода правило не влияет: `app.quit()` проходит через
/// `connect_shutdown` и при удержании, и обязательство вернуть цели
/// из паузы исполняется там же, где и раньше.
pub fn holds_application(tray_installed: bool) -> bool {
    tray_installed
}

/// Периодический такт, привязанный к окну: снимается вместе с ним.
///
/// Правило одно и обойти его нечем: такт обязан кончаться вместе со своим
/// окном. Удержание сделало приложение долгоживущим, а окно настроек
/// пересоздаётся при каждом открытии — и «трей → Настройки → крестик»,
/// повторённое N раз, оставляло N вечных источников на каждый такт. Они
/// продолжали ходить в состояние под мьютексом и пересобирать виджеты уже
/// разрушенных окон, удерживая эти окна живыми через собственные замыкания.
///
/// Своё `ControlFlow::Break` такт при этом не теряет: помощник добавляет
/// условие окна, а не подменяет условие самого такта.
///
/// Конец окна ловится по `unrealize`, и это не вкусовщина, а проверено
/// в контейнере. `destroy` у GTK4 — сигнал не закрытия, а разрушения объекта:
/// `gtk_window_destroy` его не шлёт вовсе, он приходит из `dispose`, то есть
/// когда упала последняя ссылка. А у окна настроек она не падает никогда —
/// его же кнопка держит `window.clone()` в своём обработчике, и получается
/// цикл, который GObject разорвать нечем. Такт на `connect_destroy` над таким
/// окном крутился бы вечно, то есть ровно так, как до починки. `unrealize`
/// же приходит на самом `destroy` и при этом не приходит на `hide`
/// (тоже проверено): спрятанное окно такта не теряет.
pub fn window_tick(
    window: &ApplicationWindow,
    interval: Duration,
    mut tick: impl FnMut() -> ControlFlow + 'static,
) {
    // Признак жизни отдельной ячейкой, а не ссылкой на окно: замыкание такта
    // не должно держать окно вовсе — иначе помощник сам заводил бы тот самый
    // цикл, от которого спасается.
    let alive = Rc::new(Cell::new(true));
    {
        let alive = alive.clone();
        window.connect_unrealize(move |_| alive.set(false));
    }
    gtk4::glib::timeout_add_local(interval, move || {
        if !alive.get() {
            return ControlFlow::Break;
        }
        tick()
    });
}
